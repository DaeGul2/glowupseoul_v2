function stepSheet(title, intro, rows, tail) {
  const aoa = [];
  aoa.push([title]);
  aoa.push([intro]);
  aoa.push([]);
  aoa.push(STEP_HDR);
  for (const r of rows) aoa.push(r);
  if (tail && tail.length) {
    aoa.push([]);
    for (const t of tail) aoa.push([t]);
  }
  return sheetFromRows(aoa, STEP_COLS);
}

